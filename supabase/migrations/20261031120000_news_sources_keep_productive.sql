-- Ленты, которые считались мёртвыми, живы — и выключать их было ошибкой.
--
-- Прежняя миграция (20261029150000_disable_dead_news_sources.sql) опиралась на
-- два наблюдения: «Google News отвечает 503 на каждом запуске» и «BBC World дала
-- 0 подходящих материалов из ~24 просмотренных». Первое подтверждается лишь
-- частично, второе не подтверждается вовсе. Собственные таблицы платформы за
-- 7 дней говорят другое:
--
--   reuters-google-business: 336 запусков, 51 успешный (85 % — 503 от Google
--                            News), но 402 принятых статьи; последняя — 31.10;
--   bbc-world:                336 запусков, 336 успешных, 181 принятая статья;
--                            последняя — 31.10.
--
-- 583 статьи в неделю — это не мёртвая лента. Провалы Google News видны в
-- журнале здоровья (news_source_health_v2) и стоят нескольких впустую
-- потраченных запросов, но молча терять материал дороже: сайт обещает полноту
-- выбора, а не тишину. Поэтому обе ленты включены, строки не удалялись.
--
-- Если лента действительно умрёт, это будет видно в журнале здоровья
-- (ok = false подряд), и отключать её нужно по свежим данным, а не по памяти.

update public.news_sources_v2
set enabled = true,
    updated_at = now()
where id in ('reuters-google-business', 'bbc-world');
