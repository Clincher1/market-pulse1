-- Две ленты в контуре прогнозов (V2) не работают и не могут заработать на нашей
-- стороне — это проверено прогонами, а не догадка:
--
--   reuters-google-business — Google News отвечает HTTP 503 на каждом запуске;
--   bbc-world               — лента живая, но за серию запусков дала 0 подходящих
--                             материалов из ~24 просмотренных.
--
-- Пока они включены, каждый запуск ингеста пишет строку с ошибкой и тратит
-- запросы впустую. Выключаем, сохраняя строки целиком: включить обратно — один
-- update, история и настройки не теряются.
--
-- ТАСС и РБК здесь намеренно не трогаются: они живые и выключены по решению
-- о настройке фильтра, а не потому, что мертвы.

update public.news_sources_v2
set enabled = false,
    updated_at = now()
where id in ('reuters-google-business', 'bbc-world');
