-- Подпись источника рядом с ценой.
--
-- Зачем колонка. Владелец может выбрать источник слота вручную (например,
-- Coinbase вместо Kraken для BTC). Числа на плитке тогда меняются, и если
-- подпись останется прежней, сайт выдаст цену одной площадки за цену другой —
-- это ровно та молчаливая подмена, которую проект запрещает.
--
-- Писатель цен уже знает, кого он спрашивал: провайдер есть в метаданных
-- каждого ряда. Раньше он жил только в ответе функции, теперь пишется и в
-- кэш, откуда его читает плитка.

alter table public.cached_assets add column if not exists source_label text;

comment on column public.cached_assets.source_label is
  'Как источник назван в ответе: Coinbase, Kraken, ЕЦБ. Пишется update-assets из метаданных ряда, чтобы при смене источника подпись на плитке менялась вместе с числом.';
