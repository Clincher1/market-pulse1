-- Даты наблюдений для мировых котировок.
--
-- Раньше в cached_assets лежали только значения sparkline, а даты закрытий
-- выбрасывались — и сайт честно писал, что источник их не передаёт. На самом
-- деле передаёт: FRED отдаёт observation_date, ЕЦБ — Cube time, Kraken —
-- отметку свечи, Twelve Data — datetime. Без дат нельзя сказать «третий день
-- роста», нельзя показать, к какому дню относится цена, и нельзя сравнить
-- недели по календарю.
--
-- Колонка nullable и без значения по умолчанию: пустой массив означал бы
-- «дат нет», а это утверждение. Пока функция не перезаписала строку, значения
-- остаются null, и фронтенд трактует ряд как бездатый.

alter table public.cached_assets
  add column if not exists spark_dates jsonb;

comment on column public.cached_assets.spark_dates is
  'ISO-даты наблюдений, по одной на значение sparkline, в том же порядке. null — даты не сохранены.';
