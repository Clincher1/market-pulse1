-- Дата наблюдения цены отдельно от времени записи в кэш.
--
-- Раньше у плитки было только `updated_at` — момент, когда писатель цен сходил
-- к источнику. У Brent, S&P 500 и золота источник отдаёт дневное закрытие,
-- поэтому в 08:45 МСК в кэше лежало закрытие вчерашнего дня, а подпись
-- «обновлено 08:45» приписывала цене минутную точность, которой у неё нет.
--
-- `as_of` — то, что сказал источник: дата закрытия для дневных рядов, момент
-- котировки для внутридневных. Оба поля нужны и означают разное:
--   as_of      — на какой момент верна цена;
--   updated_at — когда кэш её записал.
--
-- Колонка необязательная: писатель цен заполняет её только тогда, когда она
-- уже есть (см. update-assets), поэтому выкатка кода и применение миграции
-- не обязаны совпадать по времени.

alter table public.cached_assets
  add column if not exists as_of timestamptz;

comment on column public.cached_assets.as_of is
  'Момент, на который верна цена: дата закрытия для дневных рядов (FRED/EIA), момент котировки для внутридневных. Не заменяет updated_at — там время записи в кэш.';
