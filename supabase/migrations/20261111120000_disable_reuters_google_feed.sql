-- Reuters через Google News: выключаем, но не удаляем.
--
-- Решение принято по отрезку, а не по одному снимку. За 04-11.11.2026
-- (336 запусков крона, до пейсинга):
--   63 успешных ответа (18,8 %), 138 ответов 503, 135 запусков съела пауза;
-- после пейсинга (11.11, последние сутки): 18 успехов из 48 запусков (37,5 %),
--   17 реальных отказов 503, последний успех 05:35 UTC — то есть пять часов
--   подряд лента не отвечала вообще.
--
-- Почему всё-таки выключаем, а не терпим:
--   1. Google News — посредник, а не издатель. Все 87 ссылок за неделю
--      ведут на news.google.com/rss/articles/..., то есть на редирект Google,
--      а не на адрес Reuters. В карточке стоит «Reuters», в адресе — Google.
--   2. Доля отказов 62-81 % делает журнал здоровья шумным, а проверку
--      feeds_fresh — красной на каждом пятичасовом провале, хотя сайт
--      в это время здоров.
--   3. Цена вопроса — около 6 % объёма: 20 материалов в сутки при ~330
--      у остальных 19 лент, которые отвечают 336 из 336.
--
-- Строки не удаляются: включить обратно — один UPDATE. Статьи и их разбор
-- остаются в истории, чтобы ничего не пропало задним числом.

update public.news_sources_v2
set enabled = false,
    poll_interval_minutes = 120,
    updated_at = now()
where id = 'reuters-google-business';

comment on column public.news_sources_v2.enabled is
  'Работающая лента отвечает без отказов. Выключенная остаётся в реестре и в истории статей, чтобы решение можно было пересмотреть одним UPDATE, а не восстановлением из бэкапа.';
