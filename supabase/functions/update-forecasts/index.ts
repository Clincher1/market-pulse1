// Выдача прогнозов остановлена 31 октября 2026 года.
//
// Причина записана здесь, а не только в чате: на 26 оценённых исходах доля
// попаданий была 46,2 %, а счёт Брайера — 0,3996 против 0,25 у подбрасывания
// монетки. Прогноз, который хуже случайного, нельзя показывать как ожидание:
// это обещание, которое сайт не может выполнить.
//
// Функция оставлена живой намеренно: slug продолжает отвечать 200 и честно
// говорит, что выключен, поэтому старые вызовы из расписаний и ручные запуски
// ничего не ломают и ничего не пишут. Данные прошлых прогнозов не удаляются —
// они остаются в market_forecasts_v2 и forecast_outcomes_v2 как архив, который
// нельзя переписать задним числом.
//
// Не включайте запись прогнозов обратно без нового замера точности: возвращать
// читателю вероятности можно только тогда, когда они лучше монетки.

import { serveWithErrorReporting } from "../_shared/observability.ts";

serveWithErrorReporting("update-forecasts", () => {
  return Response.json({
    success: true,
    disabled: true,
    updated: 0,
    message:
      "Выдача прогнозов остановлена 31.10.2026: точность оказалась хуже случайной. Архив прежних записей сохранён.",
    generated_at: new Date().toISOString(),
  });
});
